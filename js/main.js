function translatePage(lang) {
    document.querySelectorAll('[data-translate]').forEach(function(el) {
        const key = el.getAttribute('data-translate');
        if (translations[lang] && translations[lang][key]) {
            el.textContent = translations[lang][key];
        }
    });
}

function openFeatureModal(featureId) {
    const modal = new bootstrap.Modal(document.getElementById('featureModal'));
    const feature = featureDetails[featureId];
    
    if (feature) {
        const lang = document.documentElement.lang || 'en';
        const titleEl = document.getElementById('featureModalTitle');
        const listEl = document.getElementById('featureModalList');
        
        if (lang === 'bn') {
            titleEl.textContent = feature.title_bn;
        } else if (lang === 'it') {
            titleEl.textContent = feature.title_it;
        } else {
            titleEl.textContent = feature.title;
        }
        
        let listHtml = '';
        feature.services.forEach(service => {
            listHtml += `
                <li>
                    <i class="fas fa-check-circle"></i>
                    <div>
                        <strong>${service.name}</strong>
                        <span>${service.desc}</span>
                    </div>
                </li>
            `;
        });
        listEl.innerHTML = listHtml;
    }
    
    modal.show();
}

// Handle Bootstrap modal show event using jQuery
$(document).ready(function() {
    // Handle Bootstrap modal show event
    $('#featureModal').on('show.bs.modal', function(event) {
        var button = $(event.relatedTarget);
        var featureId = button.data('feature');
        
        console.log('Modal triggered for feature:', featureId);
        console.log('Feature details:', featureDetails[featureId]);
        
        if (featureId && featureDetails[featureId]) {
            var feature = featureDetails[featureId];
            var lang = document.documentElement.lang || 'en';
            
            // Set title based on language
            if (lang === 'bn' && feature.title_bn) {
                $('#featureModalTitle').text(feature.title_bn);
            } else if (lang === 'it' && feature.title_it) {
                $('#featureModalTitle').text(feature.title_it);
            } else {
                $('#featureModalTitle').text(feature.title);
            }
            
            // Build services list
            var listHtml = '';
            if (feature.services && feature.services.length > 0) {
                feature.services.forEach(function(service) {
                    listHtml += '<li><i class="fas fa-check-circle"></i><div><strong>' + service.name + '</strong><span>' + service.desc + '</span></div></li>';
                });
            } else {
                listHtml = '<li class="text-center text-muted">No services available</li>';
            }
            $('#featureModalList').html(listHtml);
        } else {
            console.log('No feature details found for:', featureId);
        }
    });
    
    // Initial translations
    var currentLang = document.documentElement.lang || 'en';
    translatePage(currentLang);
});

// Stats Animation - Simple and reliable
function initStatsAnimation() {
    var counters = document.querySelectorAll('.stat-number');
    if (!counters.length) return;
    
    counters.forEach(function(counter) {
        // Skip if already animated
        if (counter.dataset.animated) return;
        
        // Get target value
        var targetStr = counter.getAttribute('data-target');
        var target = parseInt(targetStr, 10);
        
        // Skip if no valid target
        if (!target || target <= 0 || isNaN(target)) return;
        
        // Mark as animated
        counter.dataset.animated = 'true';
        
        // Animate
        var current = 0;
        var increment = target / 50;
        
        var timer = setInterval(function() {
            current += increment;
            if (current >= target) {
                counter.innerText = target + '+';
                clearInterval(timer);
            } else {
                counter.innerText = Math.floor(current);
            }
        }, 30);
    });
}

// Run on page load
document.addEventListener('DOMContentLoaded', function() {
    // Try immediately
    setTimeout(initStatsAnimation, 100);
    
    // Also try on scroll
    window.addEventListener('scroll', initStatsAnimation, { passive: true });
});

